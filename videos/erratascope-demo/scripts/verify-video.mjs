import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {createReadStream,readFileSync,writeFileSync,statSync,readdirSync} from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const file=path.resolve(root,process.argv[2]??'renders/ErrataScope_Demo_Desan_Vasu.mp4');
const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',file],{encoding:'utf8'}));
const video=probe.streams.filter(s=>s.codec_type==='video');
const audio=probe.streams.filter(s=>s.codec_type==='audio');
const edit=JSON.parse(readFileSync(path.join(root,'EDIT.json'),'utf8'));
const failures=[];
const requireFact=(ok,message)=>{if(!ok)failures.push(message)};
const duration=Number(probe.format.duration);
requireFact(video.length===1,'one video stream required');
requireFact(audio.length===0,'silent brief requires no audio stream');
requireFact(video[0]?.codec_name==='h264','H.264 required');
requireFact(video[0]?.width===1920&&video[0]?.height===1080,'1920x1080 required');
requireFact(video[0]?.pix_fmt==='yuv420p','yuv420p required');
requireFact(video[0]?.r_frame_rate==='30/1','30 fps required');
requireFact(duration>0&&duration<180,'must be less than three minutes');
requireFact(Math.abs(duration-edit.duration)<=1/30,'duration must match the accepted edit');
requireFact(Number(video[0]?.nb_frames)===edit.duration*30,'frame count must match edit');
requireFact(Math.abs(Number(video[0]?.start_time??0))<=.001,'video starts at zero');
execFileSync('ffmpeg',['-hide_banner','-v','error','-xerror','-i',file,'-map','0:v:0','-f','null','-'],{stdio:['ignore','ignore','pipe']});
const summary=JSON.parse(readFileSync(path.join(root,'assets/capture/review-summary.json'),'utf8'));
const markdown=readFileSync(path.join(root,'assets/capture/review-summary.md'),'utf8');
requireFact(summary.source.synthetic===false,'export must be actual manufacturer case');
requireFact(summary.extraction.mode==='live'&&summary.extraction.case_kind==='real_source','recorded real-source origin required');
requireFact(summary.review.latest.revision===2&&summary.review.history.length===2,'real recorded review history required');
requireFact(summary.review.latest.note.includes('does not establish applicability'),'review meaning preserved');
requireFact(summary.extraction.coverage_summary.detected_entries===53&&summary.extraction.coverage_summary.supported_selected===2,'actual coverage retained');
requireFact(markdown.includes('nvidia/Nemotron-3.5-Super-VL'),'actual model provenance retained');
requireFact(markdown.includes('Recorded live Nemotron result'),'recorded-live label retained');
const digest=async p=>{const h=createHash('sha256');for await(const c of createReadStream(p))h.update(c);return h.digest('hex')};
const captureDir=path.join(root,'assets/capture');
const captures=[];
for(const name of readdirSync(captureDir).filter(n=>/\.(mp4|webm)$/.test(n)).sort()){
 const p=path.join(captureDir,name);captures.push({file:`assets/capture/${name}`,bytes:statSync(p).size,sha256:await digest(p)});
}
const report={ok:failures.length===0,file:path.relative(root,file).replaceAll('\\','/'),bytes:statSync(file).size,sha256:await digest(file),duration_s:duration,video:{codec:video[0]?.codec_name,width:video[0]?.width,height:video[0]?.height,pixel_format:video[0]?.pix_fmt,fps:video[0]?.r_frame_rate,frames:Number(video[0]?.nb_frames)},audio_streams:audio.length,full_decode:'PASS',actual_review_export:'PASS',provider_calls_during_capture:0,source_captures:captures,failures};
writeFileSync(path.join(root,'VERIFICATION.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({...report,source_captures:`${captures.length} files hashed`},null,2));
if(failures.length)process.exitCode=1;
